"""Extend the permanent-id ledger from the installed registry.

Run ``uv run python scripts/release_ledger.py 1.0.0a2`` before a release.
``--check`` is read-only and fails if a registered id is absent. Existing
records are never removed or rewritten, including when a model is renamed.
Only core/_released.py and data/_released.py are written, as UTF-8 with LF endings.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import TYPE_CHECKING

from pyeconomics.core._released import RELEASED, Released
from pyeconomics.core.errors import RegistryError
from pyeconomics.core.registry import installed
from pyeconomics.data import catalog as concepts
from pyeconomics.data import registry as providers
from pyeconomics.data._released import CONCEPTS, PROVIDERS

if TYPE_CHECKING:
    from collections.abc import Iterable, Mapping, Sequence

    from pyeconomics.core.registry import Registry

TARGET = Path(__file__).resolve().parents[1] / "src/pyeconomics/core/_released.py"
DATA_TARGET = TARGET.parents[1] / "data/_released.py"
LINE_LENGTH = 88
VERSION = re.compile(
    r"[1-9][0-9]*\.[0-9]+\.[0-9]+(?:(?:a|b|rc)[0-9]+)?(?:\.post[0-9]+)?"
)


_TEMPLATE = '''# src/pyeconomics/core/_released.py
# Copyright 2026 Nathan Ramos, CFA
# SPDX-License-Identifier: Apache-2.0
"""The released-id ledger (ADR-0003: a released model id is permanent).

Once a release ships a model id, the id is never deleted or given to another
model. A renamed model keeps its old id as an alias. This ledger records every
id a release shipped, so ``registry.validate()`` can fail when one goes missing
or is reused.

A module holds the ledger rather than a data file because the wheel admits only
Python modules under ``pyeconomics/``. Generated by
``scripts/release_ledger.py``; never edit entries by hand.

Examples
--------
>>> from pyeconomics.core._released import RELEASED
>>> len(RELEASED)
32
"""

from __future__ import annotations

from dataclasses import dataclass
from types import MappingProxyType
from typing import TYPE_CHECKING, Final

if TYPE_CHECKING:
    from collections.abc import Mapping

__all__ = ["RELEASED", "Released"]


@dataclass(frozen=True, slots=True)
class Released:
    """What the ledger records about one released id."""

    canonical_id: str
    """The canonical id the released id named when it shipped. For an id that
    shipped as a model's own id this is the id itself; for one that shipped as
    an alias it is the model's id at that release."""
    first_version: str
    """The first package version that shipped the id, such as ``1.0.0a1``."""


'''

_DATA_TEMPLATE = '''# src/pyeconomics/data/_released.py
# Copyright 2026 Nathan Ramos, CFA
# SPDX-License-Identifier: Apache-2.0
"""The released-id ledgers of the data layer (ADR-0003: a released id is permanent).

Once a release ships a provider id or a catalog concept id, the id is never
deleted, renamed or given to another. Two sections record what each release
shipped, so ``pyeconomics.data.registry.validate()`` can fail when an id goes
missing: :data:`PROVIDERS` (rule ``released``) and :data:`CONCEPTS` (rule
``released-concept``, ADR-0011 decision 15).

A module holds the ledgers rather than a data file because the wheel admits only
Python modules under ``pyeconomics/``. Generated by
``scripts/release_ledger.py``; never edit entries by hand.

Examples
--------
>>> from pyeconomics.data._released import CONCEPTS, PROVIDERS
>>> len(PROVIDERS), len(CONCEPTS)
({provider_count}, {concept_count})
"""

from __future__ import annotations

from types import MappingProxyType
from typing import TYPE_CHECKING, Final

from pyeconomics.core._released import Released

if TYPE_CHECKING:
    from collections.abc import Mapping

__all__ = ["CONCEPTS", "PROVIDERS"]


'''


def extend(
    catalog: Registry, released: Mapping[str, Released], version: str
) -> dict[str, Released]:
    """Validate the catalog and append ids without changing release history."""
    if not VERSION.fullmatch(version):
        msg = "version must be a non-development 1.x-or-later release"
        raise ValueError(msg)
    catalog.validate(released=released)
    result = dict(released)
    for model in catalog.models():
        result.setdefault(model.id, Released(model.id, version))
        for alias in model.spec.aliases:
            result.setdefault(alias.id, Released(model.id, version))
    return dict(sorted(result.items()))


def render(released: Mapping[str, Released]) -> bytes:
    """Render the fixed module template with sorted immutable entries."""
    template = _TEMPLATE
    template = re.sub(r"(>>> len\(RELEASED\)\n)\d+", rf"\g<1>{len(released)}", template)
    return (template + _section("RELEASED", "id", released)).encode("utf-8")


def _section(name: str, kind: str, released: Mapping[str, Released]) -> str:
    """Render one immutable, sorted mapping without changing release history."""
    rows = ""
    for key, entry in sorted(released.items()):
        line = (
            f'        "{key}": Released("{entry.canonical_id}", '
            f'"{entry.first_version}"),'
        )
        if len(line) > LINE_LENGTH:
            line = (
                f'        "{key}": Released(\n'
                f'            "{entry.canonical_id}", "{entry.first_version}"\n'
                "        ),"
            )
        rows += line + "\n"
    return (
        f"#: Every released {kind} and its first package version.\n"
        "#: Generated by scripts/release_ledger.py; do not edit.\n"
        f"{name}: Final[Mapping[str, Released]] = MappingProxyType(\n"
        "    {\n" + rows + "    }\n)\n"
    )


def extend_ids(
    ids: Iterable[str], released: Mapping[str, Released], version: str
) -> dict[str, Released]:
    """Append provider or concept ids; callers validate their existing history."""
    if not VERSION.fullmatch(version):
        msg = "version must be a non-development 1.x-or-later release"
        raise ValueError(msg)
    result = dict(released)
    for name in ids:
        result.setdefault(name, Released(name, version))
    return dict(sorted(result.items()))


def render_data(
    released_providers: Mapping[str, Released],
    released_concepts: Mapping[str, Released],
) -> bytes:
    """Render both data ledgers deterministically from validated registry ids."""
    return (
        _DATA_TEMPLATE.format(
            provider_count=len(released_providers), concept_count=len(released_concepts)
        )
        + _section("PROVIDERS", "provider id", released_providers)
        + "\n"
        + _section("CONCEPTS", "catalog concept id", released_concepts)
    ).encode("utf-8")


def main(argv: Sequence[str] | None = None) -> int:
    """Write the release ledger, or check coverage without writing."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("version", nargs="?")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if not args.check and args.version is None:
        parser.error("a release version is required unless --check is used")
    catalog = installed()
    try:
        catalog.validate(released=RELEASED)
        providers.validate(released=PROVIDERS, released_concepts=CONCEPTS)
        if args.check:
            missing = sorted(
                {
                    name
                    for model in catalog.models()
                    for name in (model.id, *(a.id for a in model.spec.aliases))
                }
                - RELEASED.keys()
            )
            missing += [
                f"provider:{name}" for name in providers.ids() if name not in PROVIDERS
            ]
            missing += [
                f"concept:{name}" for name in concepts.ids() if name not in CONCEPTS
            ]
            if missing:
                sys.stderr.write(f"release-ledger: missing ids: {', '.join(missing)}\n")
                return 1
        else:
            # Validate and render every ledger before writing either module.
            models = render(extend(catalog, RELEASED, args.version))
            data = render_data(
                extend_ids(providers.ids(), PROVIDERS, args.version),
                extend_ids(concepts.ids(), CONCEPTS, args.version),
            )
            TARGET.write_bytes(models)
            DATA_TARGET.write_bytes(data)
    except (OSError, ValueError, RegistryError) as exc:
        sys.stderr.write(f"release-ledger: {exc}\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
