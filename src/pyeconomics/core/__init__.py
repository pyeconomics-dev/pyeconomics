"""The conventions every pyeconomics model encodes (ADR-0008).

This package holds numerical conventions, the date layer and the shared
numerics models build on: unit kinds and their
default bounds (:mod:`~pyeconomics.core.units`), percent and basis-point
conversion (:mod:`~pyeconomics.core.rates`), compounding
(:mod:`~pyeconomics.core.compounding`), tolerances
(:mod:`~pyeconomics.core.tolerance`), seeded randomness
(:mod:`~pyeconomics.core.random`), root finding
(:mod:`~pyeconomics.core.numerics`), cash-flow discounting and IRR
(:mod:`~pyeconomics.core.cashflows`), zero curves with forward and par rates
(:mod:`~pyeconomics.core.curves`), descriptive statistics
(:mod:`~pyeconomics.core.descriptive`), the provenance record a result keeps
of the data it read (:mod:`pyeconomics.core.provenance`, ADR-0011), and the
error and warning taxonomy (:mod:`~pyeconomics.core.errors`,
:mod:`~pyeconomics.core.warnings`). None of it does I/O: no network, file,
clock or environment access, and none of it imports :mod:`pyeconomics.data`.

Examples
--------
>>> from pyeconomics.core import Compounding, Frequency, discount_factor
>>> round(discount_factor(0.04, 5, Compounding.PERIODIC, Frequency.SEMIANNUAL), 10)
0.8203482999

"""

